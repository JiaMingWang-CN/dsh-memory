/** Install the translate function bound to the active locale. */
export function setTranslate(translate: (key: string) => string): void {
  activeTranslate = translate
}

/** Translate one key through the active locale dictionary. */
export function t(key: string): string {
  return activeTranslate(key)
}

/** Translate one key and substitute `{name}` placeholders from `vars`. */
export function formatMessage(key: string, vars: Record<string, string | number>): string {
  return activeTranslate(key).replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  )
}
